/// Toutes les icônes (aperçus, tests).
pub fn all() -> &'static [Icon] {
    &ALL
}

/// Dessine `icon` dans `rect` (carré inscrit), avec la couleur `color`.
pub fn paint(painter: &Painter, rect: Rect, icon: Icon, color: Color32) {
    let p = &Pen::new(painter, rect, color);
    match icon {
        Icon::Gallery => common::gallery(p),
        Icon::Actions => common::actions(p),
        Icon::Adjust => common::adjust(p),
        Icon::Delete => common::delete(p),
        Icon::Undo => common::history(p, false),
        Icon::Redo => common::history(p, true),
        Icon::Play => common::play(p),
        Icon::Pause => common::pause(p),
        Icon::PrevKey => common::jump_key(p, false),
        Icon::NextKey => common::jump_key(p, true),
        Icon::Key => common::key(p),
        Icon::KeyRemove => common::key_remove(p),
        Icon::Eye => common::eye(p),
        Icon::Export => common::export(p),
        Icon::Import => common::import(p),
        Icon::Save => common::save(p),
        Icon::Folder => common::folder(p),
        Icon::Settings => common::settings(p),
        Icon::Close => common::close(p),
        Icon::Check => common::check(p),
        Icon::Frame => common::frame(p),
        Icon::Grid => common::grid(p),
        Icon::Hierarchy => common::hierarchy(p),
        Icon::Bone => rigging::bone(p),
        Icon::BoneAdd => rigging::bone_add(p),
        Icon::Edit => rigging::edit(p),
        Icon::Pose => rigging::pose(p),
        Icon::Move => rigging::move_tool(p),
        Icon::Rotate => rigging::rotate(p),
        Icon::Reset => rigging::reset(p),
        Icon::Pin => rigging::pin(p),
        Icon::Select => rigging::select(p),
        Icon::Mirror => rigging::mirror(p),
        Icon::Symmetrize => rigging::symmetrize(p),
        Icon::AutoRig => rigging::auto_rig(p),
        Icon::Weights => rigging::weights(p),
        Icon::Ik => rigging::ik(p),
        Icon::Fk => rigging::fk(p),
        Icon::Ballistic => rigging::ballistic(p),
        Icon::Ghost => rigging::ghost(p),
        Icon::Trajectory => rigging::trajectory(p),
        Icon::CenterOfMass => rigging::center_of_mass(p),
        Icon::Marker => rigging::marker(p),
        Icon::Chain => rigging::chain(p),
        Icon::Mesh => rigging::mesh(p),
    }
}
