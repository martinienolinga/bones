//! Jeu d'icônes vectorielles au trait fin, dessinées avec le `Painter`
//! d'egui (aucune police d'icônes ni image à embarquer).

mod common;
mod pen;
mod rigging;

use egui::{Color32, Painter, Rect};
use pen::Pen;

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Icon {
    Gallery,
    Actions,
    Adjust,
    Bone,
    BoneAdd,
    Move,
    Rotate,
    Pin,
    Select,
    Delete,
    Undo,
    Redo,
    Play,
    Pause,
    PrevKey,
    NextKey,
    Key,
    KeyRemove,
    Mirror,
    Symmetrize,
    AutoRig,
    Weights,
    Eye,
    Hierarchy,
    Reset,
    Ballistic,
    Ghost,
    Trajectory,
    CenterOfMass,
    Export,
    Import,
    Save,
    Folder,
    Settings,
    Ik,
    Fk,
    Close,
    Check,
    Frame,
    Grid,
    Mesh,
    Marker,
    Chain,
    Pose,
    Edit,
}

